import { defineType, defineField, defineArrayMember } from 'sanity'
import { CADRES, EXPERIENCES, GROUPES, PUBLICS, SAISONS } from './listes'

const estAdmin = (user?: { roles?: { name: string }[] } | null) =>
  !!user?.roles?.some((r) => r.name === 'administrator')

export const adherentType = defineType({
  name: 'adherent',
  title: 'Adhérent',
  type: 'document',
  groups: [
    { name: 'essentiel', title: 'Essentiel', default: true },
    { name: 'fiche', title: 'Fiche détaillée' },
    { name: 'tags', title: 'Tags' },
    { name: 'lieu', title: 'Lieu' },
    { name: 'admin', title: 'Administration' },
  ],
  fields: [
    // ——— Essentiel
    defineField({
      name: 'nom',
      title: 'Nom de la structure',
      type: 'string',
      group: 'essentiel',
      description: 'Nom officiel, sans slogan.',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Slug (adresse de la fiche)',
      type: 'slug',
      group: 'essentiel',
      options: { source: 'nom', maxLength: 96 },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'branche',
      title: 'Branche officielle',
      type: 'reference',
      group: 'essentiel',
      to: [{ type: 'branche' }],
      description: 'Une des branches de l’APLPO. Détermine l’univers principal et l’étiquette sur la photo.',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'universSecondaire',
      title: 'Univers secondaire (facultatif)',
      type: 'reference',
      group: 'essentiel',
      to: [{ type: 'univers' }],
      description: 'La fiche apparaît aussi dans cet univers. Ex : Parc animalier de Casteil → Sport & Aventure (randonnée).',
    }),
    defineField({
      name: 'soustitre',
      title: 'Étiquette affichée (facultatif)',
      type: 'string',
      group: 'essentiel',
      description: 'Remplace le nom de la branche sur la photo. Ex : Parcs animaliers',
    }),
    defineField({
      name: 'siteWeb',
      title: 'Site web',
      type: 'url',
      group: 'essentiel',
      validation: (Rule) => Rule.required().warning('Le site web est requis par le cahier des charges.'),
    }),
    defineField({
      name: 'image',
      title: 'Photo principale',
      type: 'image',
      group: 'essentiel',
      description: 'Photo immersive, cadrage adapté au mobile (pas le logo).',
      options: { hotspot: true },
      validation: (Rule) => Rule.required().warning('La photo principale est requise.'),
    }),
    defineField({
      name: 'logo',
      title: 'Logo de la structure',
      type: 'image',
      group: 'essentiel',
      description: 'Fichier officiel, conservé dans le CMS (pas encore affiché sur le site).',
    }),

    // ——— Fiche détaillée
    defineField({
      name: 'galerie',
      title: 'Galerie (3 à 5 photos complémentaires)',
      type: 'array',
      group: 'fiche',
      of: [
        defineArrayMember({
          type: 'image',
          options: { hotspot: true },
          fields: [defineField({ name: 'alt', title: 'Texte alternatif', type: 'string' })],
        }),
      ],
      options: { layout: 'grid' },
      validation: (Rule) => Rule.max(5).error('5 photos maximum.'),
    }),
    defineField({
      name: 'surtitre',
      title: 'Surtitre',
      type: 'string',
      group: 'fiche',
      description: 'Petit texte en capitales au-dessus de l’accroche. Ex : Rencontre avec les animaux',
    }),
    defineField({
      name: 'accroche',
      title: 'Accroche',
      type: 'string',
      group: 'fiche',
      description: 'Une phrase différenciante, distincte de la présentation (70 caractères max). Ex : Kite & Foil - La liberté à l’état pur',
      validation: (Rule) => [
        Rule.max(70).warning('70 caractères maximum pour un affichage propre.'),
        Rule.required().warning('Accroche conseillée.'),
      ],
    }),
    defineField({
      name: 'description',
      title: 'Présentation courte',
      type: 'text',
      group: 'fiche',
      rows: 6,
      description: 'Texte factuel décrivant la structure et ses activités (600 caractères max).',
      validation: (Rule) => [
        Rule.max(600).warning('600 caractères maximum pour un affichage propre.'),
        Rule.required().warning('La présentation est requise.'),
      ],
    }),
    defineField({
      name: 'activites',
      title: 'Activités proposées',
      type: 'array',
      group: 'fiche',
      of: [defineArrayMember({ type: 'string' })],
      description: 'Activités précises, une par ligne (paddle, e-foil, canyoning…). 4 maximum.',
      validation: (Rule) => [Rule.max(4).error('4 activités maximum.'), Rule.min(1).warning('Au moins une activité.')],
    }),
    defineField({
      name: 'ctaTitre',
      title: 'Titre de l’appel à l’action',
      type: 'string',
      group: 'fiche',
      description: 'Par défaut : « Envie d’y aller ? ». Ex : Envie de les rencontrer ?',
    }),
    defineField({
      name: 'ctaTexte',
      title: 'Texte de l’appel à l’action',
      type: 'string',
      group: 'fiche',
      description: 'Par défaut : « Préparez votre visite directement auprès du professionnel. »',
    }),

    // ——— Tags
    defineField({
      name: 'publics',
      title: 'Publics (« À partager ensemble »)',
      type: 'array',
      group: 'tags',
      of: [defineArrayMember({ type: 'string' })],
      options: { list: PUBLICS, layout: 'grid' },
    }),
    defineField({
      name: 'groupes',
      title: 'Groupes accueillis (« Groupes bienvenus »)',
      type: 'array',
      group: 'tags',
      of: [defineArrayMember({ type: 'string' })],
      options: { list: GROUPES, layout: 'grid' },
    }),
    defineField({
      name: 'experiences',
      title: 'Expérience',
      type: 'array',
      group: 'tags',
      of: [defineArrayMember({ type: 'string' })],
      options: { list: EXPERIENCES, layout: 'grid' },
      description: 'Sert à la recherche et aux suggestions (non affiché sur la fiche).',
    }),
    defineField({
      name: 'cadres',
      title: 'Cadre',
      type: 'array',
      group: 'tags',
      of: [defineArrayMember({ type: 'string' })],
      options: { list: CADRES, layout: 'grid' },
      description: 'Sert à la recherche et aux filtres (non affiché sur la fiche).',
    }),
    defineField({
      name: 'periodes',
      title: 'Saisons d’ouverture',
      type: 'array',
      group: 'tags',
      of: [defineArrayMember({ type: 'string' })],
      options: { list: SAISONS, layout: 'grid' },
      description: 'Affichées en icônes ; génèrent les suggestions « À faire cet été… ».',
      validation: (Rule) => Rule.min(1).warning('Au moins une saison.'),
    }),

    // ——— Lieu
    defineField({
      name: 'itinerant',
      title: 'Activité itinérante',
      type: 'boolean',
      group: 'lieu',
      initialValue: false,
      description: 'Oui : la fiche affiche « Activité itinérante – secteur d’intervention » au lieu d’une adresse.',
    }),
    defineField({
      name: 'secteur',
      title: 'Secteur d’intervention',
      type: 'string',
      group: 'lieu',
      description: 'Ex : Tout le département, Côte Vermeille…',
      hidden: ({ document }) => !document?.itinerant,
      validation: (Rule) =>
        Rule.custom((v, ctx) => (ctx.document?.itinerant && !v ? 'Obligatoire pour une activité itinérante.' : true)),
    }),
    defineField({
      name: 'brancheActivite',
      title: 'Branche de l’activité (itinérants)',
      type: 'reference',
      group: 'lieu',
      to: [{ type: 'branche' }],
      description: 'Branche correspondant à l’activité, même si la branche administrative reste « Itinérants ». Sert à l’étiquette, à l’univers et aux suggestions.',
      hidden: ({ document }) => !document?.itinerant,
    }),
    defineField({
      name: 'ville',
      title: 'Ville',
      type: 'string',
      group: 'lieu',
      description: 'Commune du lieu de l’activité.',
      hidden: ({ document }) => !!document?.itinerant,
    }),
    defineField({
      name: 'adresse',
      title: 'Adresse du lieu de l’activité',
      type: 'text',
      rows: 2,
      group: 'lieu',
      description: 'Lieu réel d’accueil, pas le siège social. Itinérant : point de rendez-vous principal (non affiché).',
    }),
    defineField({
      name: 'localisation',
      title: 'Position GPS',
      type: 'geopoint',
      group: 'lieu',
      description: 'Sert au calcul des distances et aux activités « À proximité ».',
    }),
    defineField({
      name: 'territoires',
      title: 'Territoire(s)',
      type: 'array',
      group: 'lieu',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'territoire' }] })],
      validation: (Rule) => Rule.unique(),
    }),

    // ——— Administration
    defineField({
      name: 'dateAdhesion',
      title: 'Date d’adhésion à l’APLPO',
      type: 'date',
      group: 'admin',
      description: 'Classe les résultats sans géolocalisation (plus ancien en premier). Modifiable par les administrateurs.',
      readOnly: ({ currentUser }) => !estAdmin(currentUser),
    }),

    // ——— Anciens champs (conservés pour les données existantes, masqués s'ils sont vides)
    defineField({
      name: 'type',
      title: 'Type (ancien champ, remplacé par « Cadre »)',
      type: 'string',
      group: 'admin',
      options: { list: ['Indoor', 'Outdoor'] },
      hidden: ({ value }) => !value,
    }),
    defineField({
      name: 'saison',
      title: 'Saison (ancien champ, remplacé par « Saisons d’ouverture »)',
      type: 'string',
      group: 'admin',
      hidden: ({ value }) => !value,
    }),
    defineField({
      name: 'territoire',
      title: 'Territoire (ancien champ, remplacé par « Territoire(s) »)',
      type: 'reference',
      to: [{ type: 'territoire' }],
      group: 'admin',
      hidden: ({ value }) => !value,
    }),
    defineField({ name: 'horaires', title: 'Horaires (ancien champ)', type: 'string', group: 'admin', hidden: ({ value }) => !value }),
    defineField({ name: 'tarifs', title: 'Tarifs (ancien champ)', type: 'string', group: 'admin', hidden: ({ value }) => !value }),
  ],
  preview: {
    select: { title: 'nom', subtitle: 'branche.titre', media: 'image' },
  },
})
